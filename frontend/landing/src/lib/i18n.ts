type Key = keyof typeof en

// English, Hindi and Marathi are authored by hand: English here, Hindi and
// Marathi in src/locales/hi.json and mr.json. The other eight are machine
// translated from English (backend/translate_i18n.py -> src/locales/<lang>.json,
// pending native review). Every language but English is its own chunk, loaded
// on demand: a Hindi farmer no longer downloads Marathi with the app, and the
// other way round. English stays in the bundle as the fallback for any key.
const TABLES: Partial<Record<Lang, Partial<Record<Key, string>>>> = { en }
export const AUTHORED: Lang[] = ['en', 'hi', 'mr']
const LOCALES = import.meta.glob<{ default: Record<string, string> }>('../locales/*.json')

/** Fetch a language's strings once; resolves at once for English or one already
 *  here. True when it fetched something, so a mounted screen knows to redraw. */
export async function loadLocale(lang: Lang): Promise<boolean> {
  if (TABLES[lang]) return false
  const load = LOCALES[`../locales/${lang}.json`]
  if (!load) return false
  TABLES[lang] = (await load()).default as Partial<Record<Key, string>>
  return true
}

export type TKey = Key
export function makeT(lang: Lang) {
  return (key: Key | string): string =>
    ((TABLES[lang] ?? {}) as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key
}


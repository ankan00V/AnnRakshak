/** Where the chosen language is kept on this device. Versioned: browsers that
 *  only ever had the old Marathi default start again in English. */
export const LANG_KEY = 'ar.lang.v2'

/** The language this phone last chose, as FarmerContext's usePersistent keeps
 *  it (JSON: `"hi"`). Only a language a farmer can choose today: a code left
 *  over from one switched off (Odia) would fetch a table nobody reads and hold
 *  the first paint on it. English when none, or when storage is blocked. */
export function savedLang(): Lang {
  try {
    const raw = localStorage.getItem(LANG_KEY)
    const v: unknown = raw === null ? null : JSON.parse(raw)
    return LANGS.find((l) => l.ready && l.code === v)?.code ?? 'en'
  } catch {
    return 'en'
  }
}
